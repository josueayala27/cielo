import { z } from 'zod'

/** Allowed ticket priorities, lowest to highest. */
export const TICKET_PRIORITIES = ['low', 'medium', 'high'] as const

/** Ticket lifecycle states, in workflow order. */
export const TICKET_STATUSES = ['open', 'in_progress', 'resolved'] as const

/** Sort orders accepted by the listing endpoint. */
export const TICKET_SORTS = ['createdAt:desc', 'createdAt:asc'] as const

export const ticketPrioritySchema = z.enum(TICKET_PRIORITIES)
export const ticketStatusSchema = z.enum(TICKET_STATUSES)
export const ticketSortSchema = z.enum(TICKET_SORTS)

export type TicketPriority = z.infer<typeof ticketPrioritySchema>
export type TicketStatus = z.infer<typeof ticketStatusSchema>
export type TicketSort = z.infer<typeof ticketSortSchema>

/**
 * Builds a trimmed string schema with length bounds and human-readable messages.
 *
 * @param label - Field name shown in the error message.
 * @param min - Minimum length after trimming.
 * @param max - Maximum length after trimming.
 */
function boundedText(label: string, min: number, max: number) {
  return z
    .string({ error: `${label} is required` })
    .trim()
    .min(min, { error: `${label} must be at least ${min} characters` })
    .max(max, { error: `${label} must be at most ${max} characters` })
}

/**
 * Writable ticket fields and their validation rules (the spec's ticket model).
 * `id`, `createdAt` and `updatedAt` are generated by the server.
 */
export const ticketInputSchema = z.object({
  title: boundedText('Title', 5, 100),
  description: boundedText('Description', 10, 1000),
  customerName: boundedText('Customer name', 2, 100),
  customerEmail: z
    .string({ error: 'Customer email is required' })
    .trim()
    .toLowerCase()
    .pipe(z.email({ error: 'Customer email must be a valid email address' })),
  priority: ticketPrioritySchema,
  status: ticketStatusSchema,
})

/** Body of `POST /api/tickets`. `status` defaults to `open`. */
export const createTicketSchema = ticketInputSchema.extend({
  status: ticketStatusSchema.default('open'),
})

/** Body of `PATCH /api/tickets/:id`: any subset of the writable fields, but at least one. */
export const updateTicketSchema = ticketInputSchema
  .partial()
  .strict()
  .refine((value) => Object.keys(value).length > 0, { error: 'Provide at least one field to update' })

export type TicketInput = z.infer<typeof ticketInputSchema>
export type CreateTicketInput = z.input<typeof createTicketSchema>
export type CreateTicket = z.output<typeof createTicketSchema>
export type UpdateTicket = z.infer<typeof updateTicketSchema>

/** A persisted ticket as returned by the API. Dates are ISO-8601 strings. */
export interface Ticket extends TicketInput {
  id: string
  createdAt: string
  updatedAt: string
}
