/**
 * Writes seed/seed.sql: 30 deterministic tickets (fixed ids and dates), so every
 * environment starts from the same data. Run: `node seed/generate-seed.mjs`.
 */
import { writeFileSync } from 'node:fs'

const customers = [
  ['Ana Torres', 'ana.torres@example.com'],
  ['Luis Martínez', 'luis.martinez@example.com'],
  ['María Gómez', 'maria.gomez@example.com'],
  ['Carlos Ruiz', 'carlos.ruiz@example.com'],
  ['Sofía Herrera', 'sofia.herrera@example.com'],
  ['Diego Castillo', 'diego.castillo@example.com'],
]

const subjects = [
  ['Cannot log in to the portal', 'The login form returns "invalid credentials" even after resetting the password twice.'],
  ['Invoice shows wrong amount', 'The October invoice charges two seats but our plan only has one active user.'],
  ['Export to CSV is empty', 'Exporting the monthly report downloads a CSV file with headers but no rows.'],
  ['Slow dashboard loading', 'The dashboard takes more than 20 seconds to load every morning since last week.'],
  ['Request to change account email', 'Please move the account to our new company domain; the old mailbox is closing.'],
  ['Mobile app crashes on start', 'The Android app closes right after the splash screen on a Pixel 7 with Android 14.'],
  ['Password reset email not received', 'The reset email never arrives; checked spam and the address is correct.'],
  ['Add a second admin user', 'We need another administrator for the finance team with billing permissions.'],
  ['Webhook deliveries failing', 'Our endpoint receives no webhook calls since Monday; the log shows timeouts.'],
  ['Typo on the pricing page', 'The pricing page says "anual" instead of "annual" on the enterprise plan card.'],
]

const priorities = ['low', 'medium', 'high']
const statuses = ['open', 'in_progress', 'resolved']
const base = Date.UTC(2026, 9, 1, 14, 0, 0) // 2026-10-01T14:00:00Z
const hour = 3_600_000

const escape = (value) => `'${String(value).replaceAll("'", "''")}'`

const rows = Array.from({ length: 30 }, (_, i) => {
  const [title, description] = subjects[i % subjects.length]
  const [name, email] = customers[(i * 5) % customers.length]
  const created = new Date(base + i * 19 * hour).toISOString()
  const status = statuses[(i * 7) % statuses.length]
  const updated = status === 'open' ? created : new Date(base + i * 19 * hour + 5 * hour).toISOString()
  const id = `seed-${String(i + 1).padStart(4, '0')}`
  const values = [id, title, description, name, email, priorities[(i * 2) % 3], status, created, updated]
  return `  (${values.map(escape).join(', ')})`
})

const sql = `-- Generated by seed/generate-seed.mjs. Re-running it replaces the seed rows only.
DELETE FROM tickets WHERE id LIKE 'seed-%';
INSERT INTO tickets (id, title, description, customer_name, customer_email, priority, status, created_at, updated_at) VALUES
${rows.join(',\n')};
`

writeFileSync(new URL('./seed.sql', import.meta.url), sql)
console.log(`Wrote ${rows.length} tickets to seed/seed.sql`)
